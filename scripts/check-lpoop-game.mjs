import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
  const page=await browser.newPage({viewport:{width:1280,height:900}})
  page.on('pageerror',error=>console.log('PAGE ERROR',error.message))
  page.on('requestfailed',request=>console.log('REQUEST FAILED',request.url(),request.failure()?.errorText))
  await page.goto('http://localhost:3000',{waitUntil:'domcontentloaded'})
  await page.getByRole('status',{name:'Loading'}).waitFor({state:'hidden',timeout:90000})
  await page.waitForTimeout(2000)
  await page.getByText('Playground',{exact:true}).dispatchEvent('click')
  await page.getByRole('button',{name:'Open L(P)OOP',exact:true}).click({timeout:60000})
  const iframe=page.locator('iframe[title="L(P)OOP playable game"]')
  await iframe.waitFor()
  await page.waitForTimeout(10000)
  console.log('FRAMES',page.frames().map(frame=>frame.url()))
  await page.screenshot({path:'/private/tmp/lpoop-loading.png'})
  const game=page.frameLocator('iframe[title="L(P)OOP playable game"]').frameLocator('#game_drop')
  await game.locator('#unity-canvas').waitFor({timeout:60000})
  await game.locator('#unity-loading-bar').waitFor({state:'hidden',timeout:180000})
  await page.waitForTimeout(3000)
  await page.screenshot({path:'/private/tmp/lpoop-playable.png'})
  await game.locator('#unity-canvas').click({position:{x:480,y:450}})
  await page.waitForTimeout(2000)
  await page.screenshot({path:'/private/tmp/lpoop-playing.png'})
  await page.setViewportSize({width:800,height:650})
  await page.waitForTimeout(1000)
  const bounds=await iframe.boundingBox()
  assert(bounds.x>=0 && bounds.y>=68 && bounds.x+bounds.width<=800 && bounds.y+bounds.height<=650)
  await page.getByRole('button',{name:'Screenshots',exact:true}).click()
  assert.equal(await page.getByRole('dialog').locator('img').count(),4)
  assert.equal(await iframe.count(),0)
  await page.getByRole('button',{name:'Play game',exact:true}).click()
  await iframe.waitFor()
  await page.getByRole('button',{name:'Close collection'}).click()
  assert.equal(await iframe.count(),0)
  console.log('Game loaded, clicked Play, responsive bounds passed, screenshots toggle and close teardown passed')
} finally {await browser.close()}
