// Builds public/workers/collection-layout.js from the collection layout
// sources, so the Playground collection packing search can run in a Web Worker.
//
//   node scripts/build-layout-worker.mjs   (runs automatically before dev/build)
//
// Turbopack copies a `new Worker(new URL('./x.ts', import.meta.url))` target as
// a static file without compiling it, so the browser would receive TypeScript
// and the worker would never start. Transpiling the two pure layout modules
// here keeps lib/fitCollection.ts and lib/adaptiveCollection.ts the single
// source of truth for both the worker and the main-thread fallback.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import ts from 'typescript'

const sources = ['lib/adaptiveCollection.ts', 'lib/fitCollection.ts']

const body = sources.map(path => {
  const { outputText } = ts.transpileModule(readFileSync(path, 'utf8'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  })
  // Both modules are self-contained apart from importing each other, so the
  // imports go and the exports become plain declarations in one shared scope.
  return outputText
    .split('\n')
    .filter(line => !/^import\s/.test(line) && !/^export\s*\{\s*\};?\s*$/.test(line))
    .join('\n')
    .replace(/^export function /gm, 'function ')
}).join('\n')

const output = `// GENERATED by scripts/build-layout-worker.mjs from ${sources.join(' and ')}. Do not edit.
(() => {
${body}
self.onmessage = event => {
  const { id, ratios, width, height } = event.data
  self.postMessage({ id, rects: fitCollection(ratios, width, height) })
}
})()
`

mkdirSync('public/workers', { recursive: true })
writeFileSync('public/workers/collection-layout.js', output)
console.log(`public/workers/collection-layout.js (${(output.length / 1024).toFixed(1)} KB)`)
