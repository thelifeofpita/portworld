import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
page.on('pageerror', e => console.log('PAGE ERROR', e.message))
await page.goto((process.env.TEST_BASE_URL || 'http://localhost:3000'), { waitUntil: 'domcontentloaded' })
await page.getByText('Playground', { exact: true }).waitFor()
await page.getByRole('status', { name: 'Loading' }).waitFor({ state: 'hidden', timeout: 90000 })
await page.waitForTimeout(2000)
console.log('Loaded navigation')
await page.getByText('Playground', { exact: true }).dispatchEvent('click')
await page.getByRole('button', { name: 'Open Woodstock 29', exact: true }).waitFor({ timeout: 60000 })
await page.waitForTimeout(4000)
await page.mouse.move(0, 0)
const geometryBefore = await page.locator('[aria-label="Playground"] button').evaluateAll(cards => cards.map(c => { const r=c.getBoundingClientRect(); return [r.x,r.y,r.width,r.height] }))
await page.waitForTimeout(1700)
const geometryAfter = await page.locator('[aria-label="Playground"] button').evaluateAll(cards => cards.map(c => { const r=c.getBoundingClientRect(); return [r.x,r.y,r.width,r.height] }))
assert(geometryAfter.every((r,i)=>r.every((v,j)=>Math.abs(v-geometryBefore[i][j])<0.5)), 'Card frames must stay fixed across preview cuts')
console.log('Preview frames remain fixed')
const areas=geometryAfter.map(r=>r[2]*r[3])
assert(Math.max(...areas)/Math.min(...areas)<1.01, 'Every preview card must have equal area, regardless of aspect ratio')
console.log('All preview card areas are equal')
assert.equal(areas.length,17)
assert.equal(await page.getByRole('button',{name:'Open Se me cayó el bodegón',exact:true}).count(),1)
const gameCard = page.getByRole('button', { name: 'Open LPOOP', exact: true })
assert.equal(await gameCard.locator('img').count(),4)
const frames = new Set()
for(let i=0;i<8;i++) {
  frames.add(await gameCard.locator('img').evaluateAll(images=>images.find(img=>img.style.opacity==='1')?.getAttribute('src')))
  await page.waitForTimeout(380)
}
assert.equal(frames.size,4,'LPOOP preview must cycle through all four screenshots')
await page.screenshot({ path: '/private/tmp/playground-masonry.png' })
await page.getByRole('button', { name: 'Open Captive worlds', exact: true }).hover()
await page.waitForTimeout(700)
await page.screenshot({ path: '/private/tmp/playground-hover.png' })
await page.mouse.move(0,0)
console.log(await page.locator('button[aria-label^="Open "]').evaluateAll(cards => cards.map(c => {
  const r = c.getBoundingClientRect()
  return { name: c.getAttribute('aria-label'), width: r.width, height: r.height, inView: r.left >= 0 && r.top >= 0 && r.right <= innerWidth && r.bottom + 22 <= innerHeight }
})))
console.log('VIDEOS', await page.locator('video').evaluateAll(videos => videos.map(v => ({ src: v.getAttribute('src'), paused: v.paused, time: v.currentTime, ready: v.readyState }))))
const before = await page.locator('[aria-label="Playground"] video').evaluateAll(v => v.map(el => el.getVideoPlaybackQuality().totalVideoFrames))
await page.waitForTimeout(1200)
const after = await page.locator('[aria-label="Playground"] video').evaluateAll(v => v.map(el => el.getVideoPlaybackQuality().totalVideoFrames))
assert(after.some((frames,i) => frames > before[i]), 'Visible preview videos must advance without hover')
console.log('Visible preview videos advance without hover')
await page.getByRole('button', { name: 'Open Woodstock 29', exact: true }).click()
await page.waitForTimeout(2500)
await page.screenshot({ path: '/private/tmp/playground-woodstock.png' })
console.log('DETAIL', await page.getByRole('dialog').locator('img,video').count())
assert.equal(await page.locator('[aria-label="Playground"] small').count(),0)
assert.equal(await page.getByRole('dialog').locator('h2,small').count(),0)
const detailAreas=await page.getByRole('dialog').locator('img').evaluateAll(images=>images.map(img=>{const r=img.getBoundingClientRect();return r.width*r.height}))
assert(detailAreas.every(area=>area>0),'Every detail piece must remain visible')
const closeBounds=await page.getByRole('button',{name:'Close collection'}).boundingBox()
assert(Math.abs(closeBounds.x+closeBounds.width/2-800)<1,'Close must be horizontally centered')
await page.setViewportSize({ width: 1000, height: 650 })
await page.waitForTimeout(1200)
await page.screenshot({ path: '/private/tmp/playground-detail-small.png' })
