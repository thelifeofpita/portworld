assert.equal(pair.length, 2)
assert(Math.abs(pair[0]-pair[1])<1, 'Paired videos must share the same display height')
await page.screenshot({ path: '/private/tmp/playground-pair.png' })
console.log('Paired portrait videos have equal heights', pair)
